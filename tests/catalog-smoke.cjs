const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.join(__dirname, '..');
const csv = fs.readFileSync(path.join(root, 'data/apartments_master_v1.csv'), 'utf8').trim();
const rows = csv.split(/\r?\n/).slice(1).map(x => x.split(','));
assert.equal(rows.length, 500, 'master catalog must have 500 units');
assert.equal(new Set(rows.map(r => r[0])).size, 500, 'unit IDs must be unique');
const buildings = new Set(rows.map(r => r[3]));
assert.equal(buildings.size, 54, 'master catalog must have 54 buildings');
assert(!buildings.has('3613') && !buildings.has('3615'), 'special buildings must remain separate');
const context = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'data/apartments.js'), 'utf8'), context);
const appRows = context.window.WC_APARTMENTS;
assert.equal(appRows.length, 500);
const normalize = r => `${r.unit}|${r.number}|${r.letter}|${r.building}`;
const csvIds = new Set(rows.map(r => r.join('|')));
assert.equal(new Set(appRows.map(normalize)).size, 500);
for(const r of appRows) assert(csvIds.has(normalize(r)), 'unexpected or transformed catalog entry');
console.log('PASS: Exact catalog copy — 500 apartments, 54 buildings, zero duplicated units');
