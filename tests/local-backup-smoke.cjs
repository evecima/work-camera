const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{},Blob,TextEncoder,Date,Uint8Array,Uint32Array,DataView};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../photo-naming.js'),'utf8'),context);
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../local-backup.js'),'utf8'),context);
const backup=context.window.WC_BACKUP;
assert(backup&&typeof backup.makeZip==='function');
assert.equal(backup.crc32(new TextEncoder().encode('123456789')),0xCBF43926,'CRC32 must match standard test vector');
async function test(){
  const photos=[
    {id:'photo1',createdAt:Date.parse('2026-11-06T20:00:00Z'),createdTimezoneOffsetMinutes:300,filename:'boiler.jpg',blob:new Blob(['boiler image'],{type:'image/jpeg'}),location:{group:'buildings',building:'3615',area:'boiler',path:'3615 / Boiler Room'}},
    {id:'photo2',createdAt:Date.parse('2026-11-06T20:01:00Z'),filename:'kitchen.jpg',blob:new Blob(['kitchen image'],{type:'image/jpeg'}),location:{group:'buildings',building:'3520',area:'apartment',unit:'101',path:'Building 3520 / Apartment / Apt 101'}},
    {id:'photo3',createdAt:Date.parse('2026-11-06T20:02:00Z'),filename:'school.jpg',blob:new Blob(['school image'],{type:'image/jpeg'}),location:{group:'facilities',facility:'school',path:'3613 - Montessori School'}}
  ];
  const archive=await backup.makeZip(photos);
  const zip=Buffer.from(await archive.arrayBuffer());
  const entries=[];
  let pointer=0;
  while(zip.readUInt32LE(pointer)===0x04034B50){
    assert.equal(zip.readUInt16LE(pointer+8),0,'Store ZIP entries without compression');
    const crc=zip.readUInt32LE(pointer+14);
    const size=zip.readUInt32LE(pointer+18);
    const nameLen=zip.readUInt16LE(pointer+26);
    const extraLen=zip.readUInt16LE(pointer+28);
    const name=zip.subarray(pointer+30,pointer+30+nameLen).toString('utf8');
    const data=zip.subarray(pointer+30+nameLen+extraLen,pointer+30+nameLen+extraLen+size);
    assert.equal(backup.crc32(data),crc,'ZIP entry checksum mismatch');
    entries.push({name,data:data.toString('utf8')});
    pointer+=30+nameLen+extraLen+size;
  }
  assert.equal(entries.length,4,'3 images plus manifest');
  assert(entries.some(x=>x.name.includes('3615/Boiler Room/Building_3615_Boiler_Room_2026-11-06_15-00-00_photo1.jpg')&&x.data==='boiler image'));
  assert(entries.some(x=>x.name.includes('3520/Apartment/Apartment 101/Building_3520_Apt_101_')&&x.name.endsWith('_photo2.jpg')&&x.data==='kitchen image'));
  assert(entries.some(x=>x.name.includes('Facilities/3613 - Montessori School/Facility_3613_Montessori_School_')&&x.name.endsWith('_photo3.jpg')&&x.data==='school image'));
  const manifest=JSON.parse(entries.find(x=>x.name==='manifest.json').data);
  assert.equal(manifest.photos.length,3);
  assert.equal(manifest.photos[0].originalFilename,'boiler.jpg');
  assert.equal(manifest.photos[0].exportedFilename,'Building_3615_Boiler_Room_2026-11-06_15-00-00_photo1.jpg');
  assert.equal(manifest.photos[0].recordedTimezoneOffsetMinutes,300);
  assert.equal(manifest.photos[0].recordedAtUtc,'2026-11-06T20:00:00.000Z');
  assert.equal(zip.readUInt32LE(zip.length-22),0x06054B50,'Expected end-of-central-directory marker');
  assert.equal(zip.readUInt16LE(zip.length-12),4,'Expected four central directory entries');
  const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
  assert(html.includes('id="view-home"')&&html.includes('id="home-take-photo"')&&html.includes('id="home-my-photos"'));
  assert(html.includes('id="confirm-backup"')&&html.includes('id="clear-backed-up"'));
  assert(!html.includes('src="onedrive.js"'),'No cloud connector should run');
  assert(html.includes('id="file-camera"')&&html.includes('capture="environment"'),'System camera capture required');
  assert(html.includes('id="file-import"'),'Manual import path is required for advanced Apple Camera shots');
  for(const id of ['gallery-share','gallery-download','gallery-delete','gallery-select-visible','gallery-clear-selection','gallery-save-zip','gallery-selection-actions','select-preview-photo'])
    assert(html.includes('id="'+id+'"'),'Missing gallery action: '+id);
  assert(!html.includes('id="share-photo"')&&!html.includes('id="delete-photo"'),'Bulk actions should replace the old per-photo action buttons');
  assert(!html.includes('id="camera-video"'),'Remove custom getUserMedia camera viewfinder');
  const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
  const bulk=fs.readFileSync(path.join(__dirname,'../gallery-bulk.js'),'utf8');
  assert(bulk.includes('navigator.share({files,title:'),'Multi-file Share button must use iPhone share sheet');
  const bulkContext={window:{},document:{}};
  vm.runInNewContext(bulk,bulkContext);
  assert(typeof bulkContext.window.WC_GALLERY_BULK?.init==='function','Bulk gallery module must export initialization');
  assert(typeof bulkContext.window.WC_GALLERY_BULK?.render==='function','Bulk gallery module must export renderer');
  assert(bulk.includes("tile.addEventListener('click',()=>toggle(photo.id))"),'Tapping a thumbnail must select rather than preview');
  assert(bulk.includes("preview.addEventListener('click',()=>api.showDetails(photo))"),'Preview button must open photo details');
  assert(bulk.includes('root.WC_BACKUP.makeZip(photos)'),'Multiple downloads must produce an offline ZIP');
  assert(bulk.includes("prompt('Type DELETE"),'Batch delete must demand typed confirmation');
  assert(bulk.includes('photos.filter(p=>!p.backupVerifiedAt)'),'Unverified photos require a specific warning');
  assert(bulk.includes("store.delete(photo.id)"),'Batch delete must target only explicitly selected records');
  assert(!bulk.includes('indexedDB.deleteDatabase('),'Never destroy the photo database');
  assert(html.indexOf('gallery-bulk.js?v=3.10.0')<html.indexOf('app.js?v=3.10.0'),'Gallery module must load before app');
  assert(app.includes("$('file-camera').click()"),'Location confirmation should launch system capture immediately');
  const nativeCaptureHandler=app.slice(app.indexOf("$('open-camera').addEventListener"),app.indexOf("$('open-continuous').addEventListener"));
  assert(!nativeCaptureHandler.includes('getUserMedia'),'Native mode must not start the web camera');
  assert(app.includes("navigator.mediaDevices.getUserMedia("),'Continuous mode must request a live camera');
  assert(html.includes('id="open-continuous"')&&html.includes('id="continuous-shutter"')&&html.includes('id="continuous-video"'),'Continuous shooting controls must exist');
  assert(app.includes("await saveBlob(blob,filename)"),'Continuous shots must save to existing IndexedDB path');
  assert(app.includes("currentView==='camera'&&view!=='camera'"),'Continuous camera must stop on navigation');
  assert(app.includes("window.addEventListener('pagehide',stopContinuousCamera)"),'Continuous camera must release resources on exit');
  const captureSave = app.slice(app.indexOf('async function saveBlob('),app.indexOf('function releaseUrls('));
  assert(captureSave.includes('await addPhoto(blob,filename)'),'Accepted capture must be saved');
  assert(!captureSave.includes('showDetails('),'Saving a capture must not automatically open Photo Details');
  assert(app.includes("window.WC_GALLERY_BULK.render()"),'Main app must delegate gallery rendering to multi-select module');
  assert(html.includes('Review saved pictures in My Photos.'),'User instructions must preserve gallery-only details');
  assert(html.includes('id="runtime-version"')&&html.includes('id="refresh-app"'),'In-app version and update control must be visible');
  assert(html.includes('id="gallery-show-empty"'),'Gallery needs optional empty-building toggle');
  assert(html.includes('id="gallery-copy-details"'),'User must be able to copy descriptions if WhatsApp discards them');
  assert(bulk.includes("title:details.title,text:details.text"),'Share must pass meaningful title and text instead of generic Work Camera photo');
  assert(bulk.includes("navigator.clipboard.writeText(text)"),'Copy details must copy the full selected-photo description');
  assert(html.includes('id="gallery-folder-back"')&&html.includes('id="gallery-folder-path"'),'Gallery needs nested folder Back control and breadcrumbs');
  assert(app.includes('window.WC_GALLERY_BULK.changedFilter'),'Changing gallery location should reset folder depth');
  assert(html.includes('id="gallery-location-summary"'),'Gallery must show populated-location summary');
  assert(app.includes('buildingIds,facilities});'),'Gallery needs the unchanged building/facilities catalog');
  assert(!app.includes("for(const b of buildingIds)$('gallery-filter').append"),'Gallery must not append every empty building at startup');
  for(const script of ['app.js','local-backup.js','data/apartments.js'])
    assert(html.includes(script+'?v=3.10.0'),'Versioned JS needed: '+script);
  assert(html.includes('styles.css?v=3.10.0'),'Versioned CSS required');
  assert(html.indexOf('photo-naming.js?v=3.10.0')<html.indexOf('local-backup.js?v=3.10.0'),'Naming must load before ZIP module');
  assert(html.indexOf('photo-naming.js?v=3.10.0')<html.indexOf('gallery-bulk.js?v=3.10.0'),'Naming must load before gallery sharing');
  assert(app.includes("const APP_VERSION='3.10.0'"),'Runtime build must identify the executable JS version');
  assert(app.includes('createdTimezoneOffsetMinutes:new Date(createdAt).getTimezoneOffset()'),'New photos must retain capture-time timezone offset');
  assert(app.includes("window.location.replace(address.href)"),'Refresh should navigate without changing storage');
  assert(!app.includes('indexedDB.deleteDatabase('),'Updating must never delete the photo database');
  const worker=fs.readFileSync(path.join(__dirname,'../service-worker.js'),'utf8');
  assert(worker.includes("work-camera-shell-v3.10.0"),'New SW version required');
  assert(worker.includes('gallery-bulk.js?v=3.10.0'),'Offline cache must contain the multi-select gallery module');
  assert(worker.includes('photo-naming.js?v=3.10.0'),'Offline cache must include descriptive photo name generator');
  assert(worker.includes('apartment-lookup.js?v=3.10.0'),'Offline cache must contain the direct apartment finder');
  assert(worker.includes("fetch(event.request,{cache:'no-store'})"),'Online fetch must bypass HTTP cache');
  assert(worker.includes("cache.match('./index.html')"),'Offline fallback must remain available');
  assert(!worker.includes('indexedDB'),'SW must not modify photos');
  console.log('PASS: ZIP, photo catalog, camera modes, gallery multi-select, bulk operations and safe PWA updates');
}
test().catch(e=>{console.error(e);process.exitCode=1;});
